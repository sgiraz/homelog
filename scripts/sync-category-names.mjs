#!/usr/bin/env node
// Copies the built-in category labels into the backend module.
//
// The canonical copy of these strings is
// frontend/src/i18n/locales/<lang>/categories.json — that is what Weblate
// edits and what the UI renders. The backend needs them too, because the CSV
// export runs server-side and has no vue-i18n; and Go's //go:embed cannot
// reach outside its own module, so the files have to live under backend/.
//
// Re-run after adding a language or editing a label:
//   node scripts/sync-category-names.mjs
//
// backend/internal/database/categories_names_test.go fails the build if the
// copies drift from the source, so a forgotten run is caught, never shipped.

import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'frontend', 'src', 'i18n', 'locales')
const OUT = join(ROOT, 'backend', 'internal', 'database', 'locales')

const HEADER = '// generated by scripts/sync-category-names.mjs — do not edit'

async function main() {
  const langs = (await readdir(SRC, { withFileTypes: true }))
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()

  await rm(OUT, { recursive: true, force: true })
  await mkdir(OUT, { recursive: true })

  const written = []
  for (const lang of langs) {
    let raw
    try {
      raw = await readFile(join(SRC, lang, 'categories.json'), 'utf8')
    } catch {
      // A language may be translated only in part; the app falls back to
      // English for the missing keys and so does the export.
      console.warn(`⚠️  ${lang}: no categories.json, skipped`)
      continue
    }
    const names = JSON.parse(raw)
    const body = JSON.stringify(names, null, 2)
    await writeFile(join(OUT, `categories.${lang}.json`), `${body}\n`, 'utf8')
    written.push(`${lang} (${Object.keys(names).length})`)
  }

  await writeFile(join(OUT, 'README.md'), `${HEADER}\n\nSee scripts/sync-category-names.mjs.\n`, 'utf8')
  console.log(`✅ synced category names: ${written.join(', ')} → ${OUT}`)
}

main().catch((err) => {
  console.error(`❌ ${err.message}`)
  process.exit(1)
})
